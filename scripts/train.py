#!/usr/bin/env python3
"""Run training with the full ``asr/train.py`` argument set.

All arguments are passed through unchanged, for example::

    python scripts/train.py --dialect DZA --manifest-dir data/DZA/fbank \
      --exp-dir exp/DZA/run1 --tokenizer-model data/DZA/lang/tokenizer.model \
      --cuts-name gigaspeech3_dza_cuts_train --world-size 8

Training requires an independent
``<manifest-dir>/gigaspeech3_<dialect>_cuts_dev.jsonl.gz``; it is not
generated by the data stages and is never replaced with training cuts.

Run ``python scripts/train.py --help`` for the complete list.
"""

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASR = ROOT / "asr"


def main():
    env = os.environ.copy()
    env["PYTHONPATH"] = os.pathsep.join(
        [str(ASR), str(ASR / "zipformer"), str(ROOT), str(ROOT / "scripts")]
    ) + os.pathsep + env.get("PYTHONPATH", "")
    env["PYTHONIOENCODING"] = "utf-8"
    command = [sys.executable, str(ASR / "train.py"), *sys.argv[1:]]
    return subprocess.call(command, cwd=ROOT, env=env)


if __name__ == "__main__":
    raise SystemExit(main())
